// ----------------------------------------------------------------------------
// Implementação de Pausa Cross-Platform
// ----------------------------------------------------------------------------
void pausarMs(int ms) {
#ifdef _WIN32
    Sleep(ms);
#else
    std::this_thread::sleep_for(std::chrono::milliseconds(ms));
#endif
}

// ----------------------------------------------------------------------------
// Efeito de Digitação Teletipo (Suave e Legível)
// ----------------------------------------------------------------------------
void digitarTexto(const string& texto, int msDelay) {
    for (char c : texto) {
        cout << c << flush;
        pausarMs(msDelay);
    }
    cout << endl;
}

