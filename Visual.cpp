// ----------------------------------------------------------------------------
// Barra de Vida Colorida em ASCII
// ----------------------------------------------------------------------------
void desenharBarraVida(const string& nome, int pvAtual, int pvMaximo, int largura) {
    int preenchido = (pvMaximo > 0) ? (pvAtual * largura) / pvMaximo : 0;
    if (preenchido < 0) preenchido = 0;
    if (preenchido > largura) preenchido = largura;

    cout << Cor::NEGRITO << nome << Cor::RESET << " [";

    if (pvAtual > pvMaximo * 0.5) {
        cout << Cor::VERDE;
    } else if (pvAtual > pvMaximo * 0.2) {
        cout << Cor::AMARELO;
    } else {
        cout << Cor::VERMELHO;
    }

    for (int i = 0; i < largura; i++) {
        if (i < preenchido) cout << "█";
        else cout << "░";
    }

    cout << Cor::RESET << "] " << Cor::NEGRITO << pvAtual << "/" << pvMaximo << " PV" << Cor::RESET;
}

// ----------------------------------------------------------------------------
// Barra de Recurso (Mana / Energia)
// ----------------------------------------------------------------------------
void desenharBarraRecurso(const string& nomeRecurso, int atual, int maximo, const string& corBarra, int largura) {
    int preenchido = (maximo > 0) ? (atual * largura) / maximo : 0;
    if (preenchido < 0) preenchido = 0;
    if (preenchido > largura) preenchido = largura;

    cout << Cor::NEGRITO << nomeRecurso << Cor::RESET << " [";
    cout << corBarra;

    for (int i = 0; i < largura; i++) {
        if (i < preenchido) cout << "█";
        else cout << "░";
    }

    cout << Cor::RESET << "] " << Cor::NEGRITO << atual << "/" << maximo << Cor::RESET;
}

